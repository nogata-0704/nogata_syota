#include <iostream>

int main() {
    // 画像のデータを10x10の2次元配列として定義
    int matrix[10][10] = {
        {5, 364, 251, 751, 705, 847, 491, 121, 82, 938},
        {303, 265, 674, 868, 92, 194, 954, 244, 350, 980},
        {952, 153, 440, 475, 908, 652, 410, 719, 367, 761},
        {737, 732, 217, 842, 358, 764, 464, 570, 672, 693},
        {467, 57, 590, 256, 151, 891, 557, 536, 219, 729},
        {653, 33, 756, 98, 815, 358, 129, 403, 610, 807},
        {729, 64, 306, 677, 603, 712, 582, 375, 317, 326},
        {792, 854, 524, 76, 197, 745, 533, 61, 869, 230},
        {440, 174, 672, 845, 795, 667, 886, 677, 782, 761},
        {838, 813, 898, 383, 651, 186, 393, 305, 731, 666}
    };

    // 初期値の設定（最初の要素 [0][0] を暫定の最小・最大とする）
    int min_val = matrix[0][0];
    int min_row = 0;
    int min_col = 0;

    int max_val = matrix[0][0];
    int max_row = 0;
    int max_col = 0;

    // 2重ループで全要素をチェック
    for (int i = 0; i < 10; ++i) {        // 外側ループ：行の走査
        for (int j = 0; j < 10; ++j) {    // 内側ループ：列の走査
            int val = matrix[i][j];

            // 最小値の更新チェック
            if (val < min_val) {
                min_val = val;
                min_row = i;
                min_col = j;
            }

            // 最大値の更新チェック
            if (val > max_val) {
                max_val = val;
                max_row = i;
                max_col = j;
            }
        }
    }

    // 結果の出力
    std::cout << "最小値: " << min_val << " (行: " << min_row << ", 列: " << min_col << ")" << std::endl;
    std::cout << "最大値: " << max_val << " (行: " << max_row << ", 列: " << max_col << ")" << std::endl;

    return 0;
}